export type IconName = keyof typeof ICONS;

export function iconKey(scene: Phaser.Scene, name: string): string {
  return makeTexture(scene, `i_${name}`, 10, 10, (p) => p.map(ICONS[name] ?? ICONS.alert, L));
}

export function preloadIcons(scene: Phaser.Scene): void {
  for (const k of Object.keys(ICONS)) iconKey(scene, k);
}
